/** Зачины, которыми бот затёр ленту 05–08.10. Ими не начинаем вообще. */
export const BANNED_POST_OPENERS = [
  'Я иногда удивляюсь',
  'Сейчас поняла',
  'Тот самый момент',
  'Предприниматели, поделитесь',
  'Простите, у меня подгорает',
  'В очередной раз поняла',
];

export function startsWithBanned(text: string, extra: string[] = []): string | null {
  const head = text.trim().toLowerCase();
  for (const o of [...BANNED_POST_OPENERS, ...extra]) {
    const t = o.trim().toLowerCase();
    if (t.length >= 8 && head.startsWith(t)) return o;
  }
  return null;
}

/**
 * Формат для следующего автопоста: тот, что давнее всех не выходил, с учётом минимального промежутка.
 * history — последние автопосты: id формата и время.
 */
export function pickFormat(history: Array<{ format: string; at: number }>, now: number, formats = POST_FORMATS): PostFormat {
  const lastAt = new Map<string, number>();
  for (const h of history) lastAt.set(h.format, Math.max(lastAt.get(h.format) ?? 0, h.at));
  const allowed = formats.filter((f) => !f.minGapHours || now - (lastAt.get(f.id) ?? 0) >= f.minGapHours * 3600_000);
  const pool = allowed.length ? allowed : formats;
  // порядок списка — приоритет при равенстве (никогда не выходил → 0)
  return [...pool].sort((a, b) => (lastAt.get(a.id) ?? 0) - (lastAt.get(b.id) ?? 0))[0]!;
}

/** Первые слова недавних постов — чтобы модель не начинала одинаково. */
export function recentOpeners(posts: string[], words = 3): string[] {
  const out = new Set<string>();
  for (const p of posts) {
    const w = p.trim().split(/\s+/).slice(0, words).join(' ').replace(/[,.!?:—-]+$/, '');
    if (w) out.add(w);
  }
  return [...out];
}
